"""Top-level golden comparison: jpeg_codec_top vs the committed golden encoders.

The functional half of T1 item 5 (issue #88). Every case drives
`jpeg_codec_top` (with `sram_macro_model.v`) through the configuration and
pixel ports and compares the whole output byte for byte with the software
golden model: `jpeg_golden.encode` for colour 4:2:0 and grey, and
`qoi_golden.qoi_encode` for QOI. A mismatch is a finding; the golden model is
never adjusted to match (CLAUDE.md, spec section 11).

Inputs are the spec section 12 reference images at the CI sizes 64 x 48 and
16 x 16, regenerated by verification/images/gen_images.py. Before a case runs,
the sha256 of the generated PPM/PGM is checked against
verification/images/SHA256SUMS, so the bytes encoded are the bytes the
evidence names. JPEG cases run at qualities 10, 50, 75 and 95: the host scales
Annex K (jpeg_golden.quality_tables) and loads both DQT windows through the
configuration port, then commits (spec section 5).

Reuses the driver and the host-side block ordering of test_top_smoke.py.
"""

import hashlib
import os
import sys

import cocotb

HERE = os.path.dirname(os.path.abspath(__file__))
for sub in ("..", "../golden", "../images"):
    p = os.path.normpath(os.path.join(HERE, sub))
    if p not in sys.path:
        sys.path.insert(0, p)
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import gen_images  # noqa: E402
import jpeg_golden  # noqa: E402
import qoi_golden  # noqa: E402
from test_top_smoke import (  # noqa: E402
    Host, REG_CMD, colour_stream, grey_stream,
)

SIZES = ((64, 48), (16, 16))
QUALITIES = (10, 50, 75, 95)
DQT0, DQT1 = 0x040, 0x080
SUMS = os.path.join(HERE, "..", "images", "SHA256SUMS")

_SUMS = None
_IMAGES = {}


def _sums():
    global _SUMS
    if _SUMS is None:
        _SUMS = {}
        with open(SUMS) as f:
            for line in f:
                digest, name = line.split()
                _SUMS[name] = digest
    return _SUMS


def load_image(name, w, h):
    """(rgb, grey) bytes of a reference image, hash-checked against SHA256SUMS."""
    key = (name, w, h)
    if key not in _IMAGES:
        fn = dict(gen_images.IMAGES)[name]
        rgb = fn(w, h)
        grey = gen_images.luma(rgb)
        for fname, blob in (("%s_%dx%d.ppm" % (name, w, h), gen_images.ppm(w, h, rgb)),
                            ("%s_%dx%d_grey.pgm" % (name, w, h), gen_images.pgm(w, h, grey))):
            got = hashlib.sha256(blob).hexdigest()
            assert got == _sums()[fname], "%s does not match SHA256SUMS" % fname
        _IMAGES[key] = (rgb, grey)
    return _IMAGES[key]


def first_diff(a, b):
    return next((i for i in range(min(len(a), len(b))) if a[i] != b[i]),
                min(len(a), len(b)))


async def load_quant(host, q_luma, q_chroma):
    for i, v in enumerate(q_luma):
        await host.cfg_write(DQT0 + i, v)
    for i, v in enumerate(q_chroma):
        await host.cfg_write(DQT1 + i, v)
    await host.cfg_write(REG_CMD, 2)          # commit tables
    await host.wait_idle()
    assert host.dut.status_error.value == 0, "table commit raised an error"


async def jpeg_case(dut, mode_name, name, w, h, quality):
    rgb, grey = load_image(name, w, h)
    host = Host(dut, seed=quality)
    await host.reset()
    q_luma, q_chroma = jpeg_golden.quality_tables(quality)
    await load_quant(host, q_luma, q_chroma)
    if mode_name == "colour":
        pix = [tuple(rgb[3 * i:3 * i + 3]) for i in range(w * h)]
        got = await host.run_frame(0, w, h, colour_stream(pix, w, h))
        want = jpeg_golden.encode(list(rgb), w, h, "colour", q_luma, q_chroma)
    else:
        got = await host.run_frame(1, w, h, grey_stream(list(grey), w, h))
        want = jpeg_golden.encode(list(grey), w, h, "grey", q_luma, q_chroma)
    dut._log.info("%s %s %dx%d q%d: %d bytes, %d cycles (simulated)",
                  mode_name, name, w, h, quality, len(got), host.cycles)
    assert got == want, "%d bytes vs golden %d, first difference at index %d" % (
        len(got), len(want), first_diff(got, want))


async def qoi_case(dut, name, w, h):
    rgb, _ = load_image(name, w, h)
    host = Host(dut, seed=7)
    await host.reset()
    got = await host.run_frame(2, w, h, list(rgb))
    want = qoi_golden.qoi_encode(bytes(rgb), w, h)
    dut._log.info("qoi %s %dx%d: %d bytes, %d cycles (simulated)",
                  name, w, h, len(got), host.cycles)
    assert got == want, "%d bytes vs golden %d, first difference at index %d" % (
        len(got), len(want), first_diff(got, want))


NAMES = [n for n, _ in gen_images.IMAGES]
JPEG_PARAMS = [(n, w, h, q) for n in NAMES for (w, h) in SIZES for q in QUALITIES]
QOI_PARAMS = [(n, w, h) for n in NAMES for (w, h) in SIZES]


@cocotb.parametrize(case=JPEG_PARAMS)
async def test_colour_golden(dut, case):
    await jpeg_case(dut, "colour", *case)


@cocotb.parametrize(case=JPEG_PARAMS)
async def test_grey_golden(dut, case):
    await jpeg_case(dut, "grey", *case)


@cocotb.parametrize(case=QOI_PARAMS)
async def test_qoi_golden(dut, case):
    await qoi_case(dut, *case)
