#!/usr/bin/env python3
"""Regenerates rtl/jc_table_load_rom.v, the Annex K reset-default payload ROM.

The ROM holds the raw DQT/DHT payload bytes (spec section 5, 6 segment byte
format) packed little-endian, four bytes per 32-bit word, in the order
q0, q1, dc0, ac0, dc1, ac1 with word counts 16, 16, 7, 45, 7, 45 (spec
section 13 raw regions). Table data comes from the golden module; the bench
checks the reset result against an independent copy.

    python3 verification/rtl/gen_table_rom.py            # rewrite the file
    python3 verification/rtl/gen_table_rom.py --check    # exit 1 if stale
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "verification" / "golden"))

import jpeg_golden as g  # noqa: E402

OUT = ROOT / "rtl" / "jc_table_load_rom.v"
NWORDS = (16, 16, 7, 45, 7, 45)


def words():
    payloads = [
        bytes(g.ANNEX_K_LUMA_QUANT_ZZ),
        bytes(g.ANNEX_K_CHROMA_QUANT_ZZ),
        bytes(g.ANNEX_K_DC_LUMA_BITS) + bytes(g.ANNEX_K_DC_LUMA_VALS),
        bytes(g.ANNEX_K_AC_LUMA_BITS) + bytes(g.ANNEX_K_AC_LUMA_VALS),
        bytes(g.ANNEX_K_DC_CHROMA_BITS) + bytes(g.ANNEX_K_DC_CHROMA_VALS),
        bytes(g.ANNEX_K_AC_CHROMA_BITS) + bytes(g.ANNEX_K_AC_CHROMA_VALS),
    ]
    out = []
    for p, n in zip(payloads, NWORDS):
        p = p + bytes(4 * n - len(p))
        assert len(p) == 4 * n
        out += [int.from_bytes(p[4 * i:4 * i + 4], "little") for i in range(n)]
    return out


def render():
    w = words()
    lines = [
        "// jc_table_load_rom: Annex K reset-default table payloads (spec sections 5, 6).",
        "// GENERATED by verification/rtl/gen_table_rom.py; do not edit by hand.",
        "// Word r: q0 0..15, q1 16..31, DC0 32..38, AC0 39..83, DC1 84..90, AC1 91..135;",
        "// bytes little-endian within a word, unused tail bytes of a region are 0.",
        "`timescale 1ns / 1ps",
        "module jc_table_load_rom (",
        "    input  wire [7:0]  addr,",
        "    output reg  [31:0] data",
        ");",
        "  always @* begin",
        "    case (addr)",
    ]
    for i, v in enumerate(w):
        lines.append(f"      8'd{i}: data = 32'h{v:08x};")
    lines += ["      default: data = 32'h00000000;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
