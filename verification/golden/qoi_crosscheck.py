#!/usr/bin/env python3
"""Cross-check qoi_golden.py against the vendored, pinned qoi.h.

Compiles verification/golden/ref/qoi_ref.c with the host C compiler, then for
every 64x48 and 16x16 colour reference image (generated by
verification/images/gen_images.py) compares the Python encoder's bytes with
qoi.h's `qoi_encode` and has the harness decode the C output back to the exact
input pixels with `qoi_decode`. Grey images are out of scope (the QOI path is
RGB, spec section 8).

  qoi_crosscheck.py                 exit 0 only if every image is byte-identical
  qoi_crosscheck.py --inject-fault  negative control: perturbs the Python
                                    encoder's index hash; must exit non-zero
  --cc CC                           C compiler (default: $CC, else cc)
"""

import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "images"))

import gen_images  # noqa: E402
import qoi_golden  # noqa: E402

SMALL = ((64, 48), (16, 16))


def read_ppm(path):
    with open(path, "rb") as f:
        data = f.read()
    magic, dims, maxv, body = data.split(b"\n", 3)
    w, h = (int(v) for v in dims.split())
    assert magic == b"P6" and maxv == b"255" and len(body) == 3 * w * h
    return w, h, body


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--inject-fault", action="store_true", help="negative control")
    ap.add_argument("--cc", default=os.environ.get("CC", "cc"))
    args = ap.parse_args()

    ref = os.path.join(HERE, "ref")
    with tempfile.TemporaryDirectory(prefix="qoi_xcheck_") as tmp:
        exe = os.path.join(tmp, "qoi_ref")
        subprocess.run([args.cc, "-O2", "-Wall", "-I", ref, "-o", exe,
                        os.path.join(ref, "qoi_ref.c")], check=True)

        names = []
        for fname, data in gen_images.generate():
            if fname.endswith(".ppm") and any(
                    fname.endswith("_%dx%d.ppm" % s) for s in SMALL):
                with open(os.path.join(tmp, fname), "wb") as f:
                    f.write(data)
                names.append(fname)

        bad = 0
        for fname in names:
            w, h, rgb = read_ppm(os.path.join(tmp, fname))
            out = os.path.join(tmp, fname[:-4] + ".qoi")
            r = subprocess.run([exe, os.path.join(tmp, fname), out],
                               capture_output=True, text=True)
            with open(out, "rb") as f:
                c_bytes = f.read()
            py_bytes = qoi_golden.qoi_encode(rgb, w, h, _fault=args.inject_fault)
            same = py_bytes == c_bytes
            decoded = r.returncode == 0
            print("%-34s %6d bytes  %s  %s" % (
                fname, len(c_bytes),
                "identical" if same else "DIFFERS",
                "decodes exactly" if decoded else "DECODE FAILED"))
            if not (same and decoded):
                bad += 1
                if r.stderr:
                    print("  " + r.stderr.strip(), file=sys.stderr)

        if bad:
            print("qoi_crosscheck FAILED: %d of %d images" % (bad, len(names)),
                  file=sys.stderr)
            return 1
        print("qoi_crosscheck OK: %d images byte-identical to qoi.h, all decode exactly"
              % len(names))
        return 0


if __name__ == "__main__":
    sys.exit(main())
